`timescale 1ns/1ps

// =============================================================================
// Testbench: tb_cache_top
// Project: Direct-Mapped Cache Controller (1 KB Capacity, 16-Byte Block)
// Member: Member 5 — Top-Level Integration and Verification
//
// System-level, self-checking testbench for rtl/cache_top.v. The simulation
// model rtl/main_memory_model.v is attached to the top-level word port.
//
// Directed tests:
//   D1  Reset state: no stall/ready/memory traffic, all 64 valid bits cleared.
//   D2  Reset during an in-flight miss refill: the aborted line must not become
//       valid, and the next access must miss and return correct data.
//
// Trace tests (traces/*.trace, generated by scripts/gen_traces.py):
//   sequential, random, repeated and conflicting-address traces, each run from
//   a cold cache with memory latencies 0, 1 and 5 cycles per word.
//
// For every request the testbench checks:
//   - returned data equals the expected memory contents (trace value, cross-
//     checked against the memory model itself),
//   - hit/miss outcome equals the reference cache model in the trace,
//   - a hit generates no memory traffic, a miss exactly one 16-byte-aligned
//     block request and exactly four word reads inside that block,
//   - exactly one 1-cycle cpu_ready pulse per accepted request, no response
//     without an outstanding request, stall held for the whole transaction.
//
// Statistics per run: accepted requests, responses, hits, misses, elapsed
// cycles, hit/miss ratios, hit time, miss penalty and AMAT.
//
// Plusargs:
//   +TRACE_DIR=<dir>   trace directory (default "traces")
//   +VCD               dump waveforms to build/tb_cache_top.vcd
// =============================================================================

module tb_cache_top;

    localparam integer CLK_PERIOD_NS = 10;     // 100 MHz
    localparam integer HIT_LATENCY   = 2;      // accept edge -> response cycle
    localparam integer TIMEOUT       = 1000;   // cycles per request
    localparam integer NUM_TRACES    = 4;
    localparam integer NUM_LATENCIES = 3;
    localparam integer NUM_RUNS      = NUM_TRACES * NUM_LATENCIES;

    // -------------------------------------------------------------------------
    // DUT signals
    // -------------------------------------------------------------------------
    reg         clk;
    reg         reset;
    reg         cpu_req;
    reg  [31:0] cpu_addr;
    wire [31:0] cpu_data;
    wire        cpu_ready;
    wire        cpu_stall;

    wire        mem_word_req;
    wire [31:0] mem_word_addr;
    wire        mem_word_ready;
    wire [31:0] mem_word_data;

    // -------------------------------------------------------------------------
    // Device under test (synthesizable top) and simulation memory model
    // -------------------------------------------------------------------------
    cache_top dut (
        .clk           (clk),
        .reset         (reset),
        .cpu_req       (cpu_req),
        .cpu_addr      (cpu_addr),
        .cpu_data      (cpu_data),
        .cpu_ready     (cpu_ready),
        .cpu_stall     (cpu_stall),
        .mem_word_req  (mem_word_req),
        .mem_word_addr (mem_word_addr),
        .mem_word_ready(mem_word_ready),
        .mem_word_data (mem_word_data)
    );

    main_memory_model #(
        .DEFAULT_LATENCY(1)
    ) u_mem (
        .clk  (clk),
        .reset(reset),
        .req  (mem_word_req),
        .addr (mem_word_addr),
        .ready(mem_word_ready),
        .data (mem_word_data)
    );

    // Internal block channel between controller and refill interface
    wire        blk_req  = dut.blk_req;
    wire [31:0] blk_addr = dut.blk_addr;

    // -------------------------------------------------------------------------
    // Clock and free-running cycle counter
    // -------------------------------------------------------------------------
    initial clk = 1'b0;
    always #(CLK_PERIOD_NS / 2) clk = ~clk;

    integer cycle;
    initial cycle = 0;
    always @(posedge clk) cycle <= cycle + 1;

    // -------------------------------------------------------------------------
    // Error reporting
    // -------------------------------------------------------------------------
    integer errors;
    initial errors = 0;

    task report_error;
        input [8*96-1:0] msg;
        begin
            errors = errors + 1;
            if (errors <= 25)
                $display("  ERROR @%0t (cycle %0d): %0s", $time, cycle, msg);
            if (errors == 25)
                $display("  ... further errors suppressed");
        end
    endtask

    // -------------------------------------------------------------------------
    // Bus monitor: protocol checks and event counters (sampled on posedge)
    // -------------------------------------------------------------------------
    integer    accept_count;     // accepted CPU requests
    integer    resp_count;       // cpu_ready pulses
    integer    blk_req_count;    // block refill requests from the controller
    integer    word_req_count;   // 32-bit reads issued to backing memory
    integer    abort_count;      // requests in flight when reset was applied
    reg        outstanding;      // one request in flight
    reg [31:0] cur_addr;         // address of the request in flight
    reg        prev_ready;

    initial begin
        accept_count   = 0;
        resp_count     = 0;
        blk_req_count  = 0;
        word_req_count = 0;
        abort_count    = 0;
        outstanding    = 1'b0;
        cur_addr       = 32'd0;
        prev_ready     = 1'b0;
    end

    always @(posedge clk) begin
        if (reset) begin
            if (outstanding)
                abort_count <= abort_count + 1;
            outstanding <= 1'b0;
            prev_ready  <= 1'b0;
        end else begin
            prev_ready <= cpu_ready;

            if (cpu_req && !cpu_stall) begin
                if (outstanding)
                    report_error("request accepted while another is outstanding");
                outstanding  <= 1'b1;
                cur_addr     <= cpu_addr;
                accept_count <= accept_count + 1;
            end

            if (cpu_ready) begin
                if (!outstanding)
                    report_error("cpu_ready without an outstanding request");
                if (prev_ready)
                    report_error("cpu_ready held for more than one cycle");
                outstanding <= 1'b0;
                resp_count  <= resp_count + 1;
            end

            if (outstanding && !cpu_stall)
                report_error("cpu_stall dropped before the response");

            if (blk_req) begin
                if (!outstanding)
                    report_error("block request without an outstanding CPU request");
                if (blk_addr !== {cur_addr[31:4], 4'b0000})
                    report_error("block request address is not the aligned request block");
                blk_req_count <= blk_req_count + 1;
            end

            if (mem_word_req) begin
                if (mem_word_addr[1:0] !== 2'b00)
                    report_error("memory word address is not word aligned");
                if (mem_word_addr[31:4] !== cur_addr[31:4])
                    report_error("memory word read outside the requested block");
                word_req_count <= word_req_count + 1;
            end
        end
    end

    // -------------------------------------------------------------------------
    // CPU driver: one blocking read, returns data, latency and hit/miss
    // -------------------------------------------------------------------------
    task cpu_read;
        input  [31:0] addr;
        output [31:0] data;
        output integer latency;
        output        was_hit;
        integer t_accept;
        integer blk_before;
        integer word_before;
        integer wait_cycles;
        begin
            // Present the request between clock edges
            @(negedge clk);
            cpu_addr = addr;
            cpu_req  = 1'b1;

            // Accepted on the first rising edge with cpu_stall low
            @(posedge clk);
            wait_cycles = 0;
            while (cpu_stall && wait_cycles < TIMEOUT) begin
                @(posedge clk);
                wait_cycles = wait_cycles + 1;
            end
            t_accept    = cycle;
            blk_before  = blk_req_count;
            word_before = word_req_count;

            // Drop the request and scramble the address bus: the controller
            // must work from its latched copy of the address.
            @(negedge clk);
            cpu_req  = 1'b0;
            cpu_addr = ~addr;

            wait_cycles = 0;
            while (!cpu_ready && wait_cycles < TIMEOUT) begin
                @(negedge clk);
                wait_cycles = wait_cycles + 1;
            end
            if (!cpu_ready) begin
                $display("  FATAL: request 0x%08h timed out", addr);
                $fatal(1, "FAIL: tb_cache_top timeout");
            end

            data    = cpu_data;
            latency = cycle - t_accept;

            // Monitor counters for this transaction (no traffic can be in
            // flight during the response cycle)
            case (blk_req_count - blk_before)
                0: was_hit = 1'b1;
                1: was_hit = 1'b0;
                default: begin
                    was_hit = 1'b0;
                    report_error("more than one block request for a single miss");
                end
            endcase

            if (was_hit && (word_req_count != word_before))
                report_error("memory traffic during a cache hit");
            if (!was_hit && (word_req_count - word_before != 4))
                report_error("miss refill did not read exactly four words");
            if (was_hit && latency != HIT_LATENCY)
                report_error("hit latency differs from the expected 2 cycles");
        end
    endtask

    // -------------------------------------------------------------------------
    // Reset helper: clears the cache (all valid bits) -> cold start
    // -------------------------------------------------------------------------
    task apply_reset;
        begin
            @(negedge clk);
            cpu_req  = 1'b0;
            cpu_addr = 32'd0;
            reset    = 1'b1;
            @(negedge clk);
            @(negedge clk);
            reset    = 1'b0;
        end
    endtask

    task check_cold_cache;
        integer i;
        integer valid_count;
        begin
            valid_count = 0;
            for (i = 0; i < 64; i = i + 1)
                if (dut.u_cache_controller.u_valid_ram.ram[i] !== 1'b0)
                    valid_count = valid_count + 1;
            if (valid_count != 0)
                report_error("valid bits not cleared by reset");
        end
    endtask

    // -------------------------------------------------------------------------
    // Per-run statistics (kept for the final summary table)
    // -------------------------------------------------------------------------
    integer run_trc     [0:NUM_RUNS-1];
    integer run_latency [0:NUM_RUNS-1];
    integer run_reqs    [0:NUM_RUNS-1];
    integer run_hits    [0:NUM_RUNS-1];
    integer run_misses  [0:NUM_RUNS-1];
    integer run_cycles  [0:NUM_RUNS-1];
    integer run_hit_lat [0:NUM_RUNS-1];   // sum of hit latencies
    integer run_miss_lat[0:NUM_RUNS-1];   // sum of miss latencies

    function [8*10-1:0] trace_name;
        input integer t;
        begin
            case (t)
                0: trace_name = "sequential";
                1: trace_name = "random";
                2: trace_name = "repeated";
                default: trace_name = "conflict";
            endcase
        end
    endfunction

    function integer latency_value;
        input integer l;
        begin
            case (l)
                0: latency_value = 0;
                1: latency_value = 1;
                default: latency_value = 5;
            endcase
        end
    endfunction

    // -------------------------------------------------------------------------
    // Run one trace file at one memory latency
    // -------------------------------------------------------------------------
    reg [8*256-1:0] trace_dir;

    task run_trace;
        input integer run;
        input integer t;
        input integer mem_latency;
        reg [8*10-1:0]  name;
        reg [8*300-1:0] path;
        integer       fd;
        integer       n;
        integer       r;
        reg [8*256-1:0] line;
        reg [31:0]    t_addr;
        reg [31:0]    t_data;
        integer       t_hit;
        reg [31:0]    got;
        integer       lat;
        reg           hit;
        integer       reqs, hits, misses, hit_lat, miss_lat;
        integer       accept0, resp0, start_cycle, err0;
        begin
            name = trace_name(t);
            $sformat(path, "%0s/%0s.trace", trace_dir, name);

            fd = $fopen(path, "r");
            if (fd == 0)
                $fatal(1, "FAIL: cannot open trace file %0s (run scripts/gen_traces.py)", path);

            u_mem.set_latency(mem_latency);
            apply_reset;
            check_cold_cache;

            reqs = 0; hits = 0; misses = 0; hit_lat = 0; miss_lat = 0;
            accept0 = accept_count;
            resp0   = resp_count;
            err0    = errors;
            start_cycle = cycle;

            while (!$feof(fd)) begin
                r = $fgets(line, fd);
                if (r > 0) begin
                    n = $sscanf(line, "%h %h %d", t_addr, t_data, t_hit);
                    if (n == 3) begin
                        // Trace's expected data must match the memory model
                        if (u_mem.read_word(t_addr) !== t_data)
                            report_error("trace expected data disagrees with memory model");

                        cpu_read(t_addr, got, lat, hit);
                        reqs = reqs + 1;

                        if (got !== t_data) begin
                            report_error("returned data mismatch");
                            $display("         addr 0x%08h expected 0x%08h got 0x%08h",
                                     t_addr, t_data, got);
                        end
                        if (hit !== t_hit[0]) begin
                            report_error("hit/miss outcome differs from reference cache");
                            $display("         addr 0x%08h expected %s got %s", t_addr,
                                     t_hit ? "HIT" : "MISS", hit ? "HIT" : "MISS");
                        end

                        if (hit) begin
                            hits    = hits + 1;
                            hit_lat = hit_lat + lat;
                        end else begin
                            misses   = misses + 1;
                            miss_lat = miss_lat + lat;
                        end
                    end
                end
            end
            $fclose(fd);

            // Let the monitor register the final response
            @(posedge clk);
            @(negedge clk);

            if (accept_count - accept0 != reqs)
                report_error("accepted request count differs from issued requests");
            if (resp_count - resp0 != reqs)
                report_error("response count differs from accepted requests");

            run_trc[run]    = t;
            run_latency[run]  = mem_latency;
            run_reqs[run]     = reqs;
            run_hits[run]     = hits;
            run_misses[run]   = misses;
            run_cycles[run]   = cycle - start_cycle;
            run_hit_lat[run]  = hit_lat;
            run_miss_lat[run] = miss_lat;

            $display("  %-10s  mem latency %0d : %4d requests  %4d hits  %4d misses  %6d cycles  %0s",
                     name, mem_latency, reqs, hits, misses, cycle - start_cycle,
                     (errors == err0) ? "OK" : "ERRORS");
        end
    endtask

    // -------------------------------------------------------------------------
    // Directed tests
    // -------------------------------------------------------------------------
    task directed_tests;
        reg [31:0] got;
        integer    lat;
        reg        hit;
        integer    i;
        begin
            // D1: reset state
            $display("[D1] Reset state");
            u_mem.set_latency(1);
            apply_reset;
            @(posedge clk); #1;
            if (cpu_stall !== 1'b0)    report_error("cpu_stall high after reset");
            if (cpu_ready !== 1'b0)    report_error("cpu_ready high after reset");
            if (mem_word_req !== 1'b0) report_error("memory request after reset");
            check_cold_cache;

            // D2: reset in the middle of a miss refill
            $display("[D2] Reset during an in-flight miss refill");
            u_mem.set_latency(5);
            @(negedge clk);
            cpu_addr = 32'h0005_0124;
            cpu_req  = 1'b1;
            @(negedge clk);
            cpu_req  = 1'b0;
            for (i = 0; i < 12; i = i + 1) @(negedge clk);   // inside word fetches
            if (!cpu_stall || !dut.u_main_memory_interface.state)
                report_error("D2 setup: refill not in progress");
            apply_reset;
            check_cold_cache;

            cpu_read(32'h0005_0124, got, lat, hit);
            if (hit)                          report_error("D2: aborted line reported as hit");
            if (got !== u_mem.read_word(32'h0005_0124))
                report_error("D2: wrong data after reset recovery");
            cpu_read(32'h0005_0128, got, lat, hit);
            if (!hit)                         report_error("D2: refilled line did not hit");
            if (got !== u_mem.read_word(32'h0005_0128))
                report_error("D2: wrong data on post-recovery hit");
        end
    endtask

    // -------------------------------------------------------------------------
    // Main sequence
    // -------------------------------------------------------------------------
    integer t, l, run;
    integer tot_reqs, tot_hits, tot_misses;
    real    hit_ratio, miss_ratio, hit_time, miss_time, miss_penalty, amat, amat_meas;

    initial begin
        reset    = 1'b1;
        cpu_req  = 1'b0;
        cpu_addr = 32'd0;

        if (!$value$plusargs("TRACE_DIR=%s", trace_dir))
            trace_dir = "traces";
        if ($test$plusargs("VCD")) begin
            $dumpfile("build/tb_cache_top.vcd");
            $dumpvars(0, tb_cache_top);
        end

        $display("==========================================================================");
        $display("Member 5: cache_top system-level verification");
        $display("==========================================================================");

        directed_tests;

        $display("[T] Trace-driven tests (cold cache at the start of every run)");
        run = 0;
        for (t = 0; t < NUM_TRACES; t = t + 1) begin
            for (l = 0; l < NUM_LATENCIES; l = l + 1) begin
                run_trace(run, t, latency_value(l));
                run = run + 1;
            end
        end

        // ---------------------------------------------------------------------
        // Performance summary
        //   hit time      = average cycles from acceptance to data on a hit
        //   miss penalty  = average miss latency - hit time
        //   AMAT          = hit time + miss ratio * miss penalty
        // ---------------------------------------------------------------------
        $display("");
        $display("Performance summary (clock %0d ns; latencies in cycles from request acceptance to data)",
                 CLK_PERIOD_NS);
        $display("--------------------------------------------------------------------------------------------------");
        $display("trace       mem_lat  requests  hits  misses  hit%%    miss%%   hit_t  miss_pen  AMAT    AMAT(ns)  elapsed");
        $display("--------------------------------------------------------------------------------------------------");
        tot_reqs = 0; tot_hits = 0; tot_misses = 0;
        for (run = 0; run < NUM_RUNS; run = run + 1) begin
            hit_ratio    = run_hits[run]   * 1.0 / run_reqs[run];
            miss_ratio   = run_misses[run] * 1.0 / run_reqs[run];
            hit_time     = (run_hits[run] > 0) ? run_hit_lat[run] * 1.0 / run_hits[run]
                                               : HIT_LATENCY * 1.0;
            miss_time    = (run_misses[run] > 0) ? run_miss_lat[run] * 1.0 / run_misses[run]
                                                 : hit_time;
            miss_penalty = miss_time - hit_time;
            amat         = hit_time + miss_ratio * miss_penalty;
            amat_meas    = (run_hit_lat[run] + run_miss_lat[run]) * 1.0 / run_reqs[run];
            if ((amat - amat_meas) > 0.001 || (amat_meas - amat) > 0.001)
                report_error("AMAT formula disagrees with measured average latency");

            $display("%-10s  %5d    %6d  %5d  %6d  %6.2f  %6.2f  %5.2f  %8.2f  %6.3f  %8.2f  %7d",
                     trace_name(run_trc[run]), run_latency[run], run_reqs[run],
                     run_hits[run], run_misses[run], 100.0 * hit_ratio, 100.0 * miss_ratio,
                     hit_time, miss_penalty, amat, amat * CLK_PERIOD_NS, run_cycles[run]);
            tot_reqs   = tot_reqs + run_reqs[run];
            tot_hits   = tot_hits + run_hits[run];
            tot_misses = tot_misses + run_misses[run];
        end
        $display("--------------------------------------------------------------------------------------------------");
        $display("Total: %0d requests accepted, %0d responses, %0d aborted by reset (D2), %0d trace hits, %0d trace misses",
                 accept_count, resp_count, abort_count, tot_hits, tot_misses);
        $display("       %0d block refills, %0d memory word reads", blk_req_count, word_req_count);

        if (accept_count != resp_count + abort_count)
            report_error("accepted requests != responses + reset-aborted requests");
        if (abort_count != 1)
            report_error("expected exactly one reset-aborted request (D2)");

        $display("==========================================================================");
        if (errors == 0) begin
            $display("PASS: Member 5 cache_top system tests all PASSED (%0d trace requests)", tot_reqs);
            $display("==========================================================================");
            $finish;
        end else begin
            $display("FAIL: %0d error(s)", errors);
            $display("==========================================================================");
            $fatal(1, "FAIL: tb_cache_top");
        end
    end

endmodule
